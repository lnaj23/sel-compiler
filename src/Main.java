
import java.io.FileNotFoundException;
import java.io.FileReader;
import java.io.IOException;
import java.util.ArrayList;

class UnkownLexicalUnitException extends Exception {
   public UnkownLexicalUnitException() {
      super();
   }
}

public class Main {
	public static void main(String args[]) {
      // List of lexical units encountered. You will probably
      // be interested in a list of something else for the
      // project ;)
      ArrayList<LexicalUnit> lexicalUnits = new ArrayList<LexicalUnit>();
      
      // Type name is defined by the %class in the .flex
      // file (here, %class Lexer was used).
		Lexer lexer;
      
		try {
         // The lexer need to be initialized with a Reader
         // object such as a FileReader for instance.
			lexer = new Lexer(new FileReader("text.txt"));
         
			LexicalUnit unit;
			do {
            // By default, the lexer gives the next token
            // by calling the yylex() method. You can
            // change that name using %function <NewName>
            // in the .flex file.
            //
            // The type of the returned value can be
            // chosen by using %type <ReturnType>. It is
            // an int by default (negative when the end
            // of file/stream is reached). You will have
            // to specify the value returned when an end
            // of stream is met with "%eofval{ return ...;
            // %eofval}" if you use %type.
            //
            // To throw exceptions with the lexer, you
            // can use, in your flex file, the directive
            // %yylexthrow <Exception>.
				unit = lexer.nextToken();
            
            lexicalUnits.add(unit);
				System.out.println("<" + unit.name() + ">");
			} while (unit != LexicalUnit.EOS);
				
		} catch (FileNotFoundException e) {
			// Exception for the FileReader().
			e.printStackTrace();
		} catch (IOException e) {
			// Thrown by the Lexer generated by JFlex.
			e.printStackTrace();
		} catch (UnkownLexicalUnitException e) {
         // Thrown by us if an unknwon lexical unit is seen.
         System.err.println("UnkownLexicalUnitException...");
      }
	}
}
