import java.io.FileReader;
import java.io.FileWriter;
import java.io.FileNotFoundException;
import java.io.IOException;

/**
 *
 * Project Part 1: Lexical Analyzer
 *
 * @author Sarah Winter, Marie Van Den Bogaard, Léo Exibard, Gilles Geeraerts
 *
 */
public class Main {
    /**
     * Default constructor (so Javadoc doesn't scream).
     * Do not use.
     */
    private Main() {
        // Not to be used, this is a Main class.
    }

    /**
     *
     * The scanner
     *
     * @param args The argument(s) given to the program
     * @throws IOException           java.io.IOException if an I/O-Error occurs
     * @throws FileNotFoundException java.io.FileNotFoundException if the specified
     *                               file does not exist
     *
     */
    public static void main(String[] args) throws FileNotFoundException, IOException, SecurityException {

        // Parse command-line arguments
        String sourceFile = null;
        String texFile = null;

        if (args.length == 1) {
            // No -wt option, just the source file
            sourceFile = args[0];
        } else if (args.length == 3 && args[0].equals("-wt")) {
            // -wt option: write parse tree to tex file
            texFile = args[1];
            sourceFile = args[2];
        } else {
            // Display the usage when the number of arguments is wrong
            System.out.println("Usage:  java -jar part2.jar sourceFile.sel\n"
                    + "or\tjava -jar part2.jar -wt output.tex sourceFile.sel");
            System.exit(0);
        }

        // Open the file given in argument
        FileReader source = new FileReader(sourceFile);

        /**
         * The lexer generated by <a href="http://www.jflex.de/">JFlex</a>
         */
        final LexicalAnalyzer analyzer = new LexicalAnalyzer(source);
        final Parser parser = new Parser(analyzer);
        final ParseTree tree = parser.parse();

        // Print the leftmost derivation on stdout
        System.out.println(parser.getDerivation());

        // Write the parse tree as a LaTeX file if given in command line
        if (texFile != null) {
            try (FileWriter fw = new FileWriter(texFile)) {
                fw.write(tree.toLaTeX());
            } catch (IOException e) {
                System.err.println("Cannot write file: " + e.getMessage());
            }
        }
    }
}
